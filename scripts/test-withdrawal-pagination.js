const assert = require("node:assert/strict");
const { randomUUID } = require("node:crypto");
const test = require("node:test");
const express = require("express");
const jwt = require("jsonwebtoken");
const mongoose = require("mongoose");
const User = require("../src/models/User");
const Withdrawal = require("../src/models/WithdrawalRequest");

const port = process.env.UREMO_TEST_MONGO_PORT;
test("operators can reach and approve the oldest withdrawal across tied timestamps and historic rows", { skip: !port }, async t => {
  assert.match(port, /^\d{1,5}$/);
  await mongoose.connect(`mongodb://127.0.0.1:${port}/uremo_test_${randomUUID().replaceAll("-", "")}`);
  t.after(async () => { await mongoose.connection.dropDatabase(); await mongoose.disconnect(); });
  process.env.JWT_SECRET = randomUUID();
  const admin = await User.create({ name: "Reviewer", email: "review@example.test", role: "admin", password: randomUUID() });
  const user = await User.create({ name: "Worker", email: "worker@example.test", password: randomUUID() });
  const app = express();
  app.use(express.json());
  app.use("/api/admin/wallet", require("../src/routes/admin.wallet.routes"));
  const server = app.listen(0, "127.0.0.1");
  await new Promise(resolve => server.once("listening", resolve));
  t.after(() => new Promise(resolve => server.close(resolve)));
  const url = "http://127.0.0.1:" + server.address().port + "/api/admin/wallet/withdrawals";
  const headers = { authorization: "Bearer " + jwt.sign({ id: String(admin._id), role: "admin" }, process.env.JWT_SECRET), "content-type": "application/json" };
  const row = { userId: user._id, amount: 12, status: "pending" };
  const oldest = (await Withdrawal.collection.insertOne({ ...row })).insertedId;
  const same = new Date();
  await Withdrawal.collection.insertMany(Array.from({ length: 104 }, () => ({ ...row, createdAt: same })));
  await Withdrawal.create({ ...row, status: "paid" });
  const first = await (await fetch(url + "?status=pending", { headers })).json();
  assert.equal(first.withdrawals.length, 100);
  assert.ok(first.nextCursor);
  await Withdrawal.create(row);
  const second = await (await fetch(url + "?status=pending&before=" + encodeURIComponent(first.nextCursor), { headers })).json();
  assert.equal(second.nextCursor, null);
  assert.equal(second.withdrawals.length, 5);
  assert.equal(second.withdrawals.at(-1)._id, String(oldest));
  assert.equal(new Set([...first.withdrawals, ...second.withdrawals].map(item => item._id)).size, 105);
  assert.equal((await fetch(url + "?before=bogus", { headers })).status, 400);
  const approve = await fetch(url + "/" + oldest + "/approve", { headers, method: "PUT", body: JSON.stringify({ adminNote: "Reviewed" }) });
  assert.equal(approve.status, 200);
  assert.equal((await Withdrawal.findById(oldest)).status, "approved");
});
